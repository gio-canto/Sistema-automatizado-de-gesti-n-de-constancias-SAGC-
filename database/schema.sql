-- Reserva atómica del siguiente folio.
-- Una llamada RPC se ejecuta dentro de una transacción PostgreSQL.
create or replace function public.asignar_siguiente_folio(
  p_fecha_emision date
)
returns text
language plpgsql
set search_path = public
as $$
declare
  v_anio smallint;
  v_serie char(1);
  v_ultimo smallint;
  v_siguiente smallint;
begin
  if p_fecha_emision is null then
    raise exception 'FECHA_EMISION_REQUERIDA';
  end if;

  v_anio := extract(year from p_fecha_emision)::smallint;

  insert into public.contador_folios (anio, serie, ultimo_valor)
  values (v_anio, 'A', 0)
  on conflict (anio) do nothing;

  select serie, ultimo_valor
    into v_serie, v_ultimo
  from public.contador_folios
  where anio = v_anio
  for update;

  if v_ultimo < 9999 then
    v_siguiente := v_ultimo + 1;
  else
    if v_serie = 'Z' then
      raise exception 'FOLIOS_AGOTADOS:%', v_anio;
    end if;

    v_serie := chr(ascii(v_serie) + 1);
    v_siguiente := 1;
  end if;

  update public.contador_folios
  set
    serie = v_serie,
    ultimo_valor = v_siguiente
  where anio = v_anio;

  return concat(
    v_anio::text,
    '-',
    v_serie,
    '-',
    lpad(v_siguiente::text, 4, '0')
  );
end;
$$;

