-- ---------------------------------------------------------------------
-- 10. HEALTH CHECK PARA LA API
-- ---------------------------------------------------------------------

create or replace function public.sagc_healthcheck()
returns jsonb
language sql
stable
set search_path = public
as $$
  select jsonb_build_object(
    'provider', 'Supabase',
    'database', 'PostgreSQL',
    'schema', current_schema(),
    'server_time', now()
  );
$$;

-- ---------------------------------------------------------------------
-- 11. SEGURIDAD SUPABASE
-- ---------------------------------------------------------------------
-- SAGC accede a las tablas exclusivamente desde su backend Express
-- usando una clave secreta de Supabase. No se habilita acceso directo
-- anon/authenticated por Data API en esta etapa.

alter table public.usuarios enable row level security;
alter table public.tipos_documento enable row level security;
alter table public.eventos enable row level security;
alter table public.textos_evento enable row level security;
alter table public.campos_evento enable row level security;
alter table public.plantillas enable row level security;
alter table public.contador_folios enable row level security;
alter table public.constancias enable row level security;
alter table public.auditoria enable row level security;

revoke all on table
  public.usuarios,
  public.tipos_documento,
  public.eventos,
  public.textos_evento,
  public.campos_evento,
  public.plantillas,
  public.contador_folios,
  public.constancias,
  public.auditoria
from anon, authenticated;

grant select, insert, update, delete on table
  public.usuarios,
  public.tipos_documento,
  public.eventos,
  public.textos_evento,
  public.campos_evento,
  public.plantillas,
  public.contador_folios,
  public.constancias,
  public.auditoria
to service_role;

grant usage, select on all sequences in schema public to service_role;

revoke execute on function public.asignar_siguiente_folio(date)
  from public, anon, authenticated;
grant execute on function public.asignar_siguiente_folio(date)
  to service_role;

revoke execute on function public.sagc_healthcheck()
  from public, anon, authenticated;
grant execute on function public.sagc_healthcheck()
  to service_role;

commit;