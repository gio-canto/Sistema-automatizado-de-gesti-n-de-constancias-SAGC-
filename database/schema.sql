create table if not exists public.contador_folios (
  anio smallint primary key
    check (anio between 1000 and 9999),
  serie char(1) not null default 'A'
    check (serie between 'A' and 'Z'),
  ultimo_valor smallint not null default 0
    check (ultimo_valor between 0 and 9999),
  fecha_actualizacion timestamptz not null default now()
);

drop trigger if exists trg_contador_folios_fecha_actualizacion
  on public.contador_folios;
