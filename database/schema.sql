create table if not exists public.usuarios (
  id_usuario bigint generated by default as identity primary key,
  nombre varchar(180) not null,
  usuario varchar(100) not null unique,
  password_hash varchar(255) not null,
  permiso varchar(10) not null default 'NORMAL'
    check (permiso in ('NORMAL', 'ADMIN')),
  foto_url text,
  activo boolean not null default true,
  fecha_creacion timestamptz not null default now(),
  fecha_actualizacion timestamptz not null default now()
);

create index if not exists idx_usuarios_activo
  on public.usuarios (activo);

create index if not exists idx_usuarios_permiso
  on public.usuarios (permiso);

drop trigger if exists trg_usuarios_fecha_actualizacion on public.usuarios;
create trigger trg_usuarios_fecha_actualizacion
before update on public.usuarios
for each row execute function public.sagc_set_fecha_actualizacion();

