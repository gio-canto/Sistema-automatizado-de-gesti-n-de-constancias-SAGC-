-- ---------------------------------------------------------------------
-- Utilidad para fecha_actualizacion
-- ---------------------------------------------------------------------

create or replace function public.sagc_set_fecha_actualizacion()
returns trigger
language plpgsql
as $$
begin
  new.fecha_actualizacion = now();
  return new;
end;
$$;

