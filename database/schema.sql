create table if not exists public.constancias (
  id_constancia bigint generated by default as identity primary key,
  id_evento bigint not null references public.eventos(id_evento)
    on update cascade on delete restrict,
  id_tipo_documento bigint not null references public.tipos_documento(id_tipo_documento)
    on update cascade on delete restrict,
  id_plantilla bigint references public.plantillas(id_plantilla)
    on update cascade on delete set null,
  nombre_persona varchar(220) not null,
  datos_variables jsonb,
  folio varchar(11) not null unique
    check (folio ~ '^[0-9]{4}-[A-Z]-[0-9]{4}$')
    check (right(folio, 4)::integer between 1 and 9999),
  -- Token Único SAGC V1 · UUID versión 4 (RFC 9562)
  token_unico uuid not null unique,
  cadena_validacion text not null,
  qr_destino text not null,
  fecha_emision timestamptz not null default now(),
  emitido_por bigint not null references public.usuarios(id_usuario)
    on update cascade on delete restrict,
  estado varchar(12) not null default 'EMITIDA'
    check (estado in ('EMITIDA', 'CANCELADA', 'REEXPEDIDA')),
  id_constancia_origen bigint references public.constancias(id_constancia)
    on update cascade on delete set null,
  motivo_cancelacion varchar(500),
  fecha_cancelacion timestamptz,
  fecha_actualizacion timestamptz not null default now()
);

create index if not exists idx_constancias_evento
  on public.constancias (id_evento);

